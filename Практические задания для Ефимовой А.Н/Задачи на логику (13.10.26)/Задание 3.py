# Расстояние от А до Г
ag = 10
# Расстояние от Г до Б
gb = 11
# Расстояние от А до Б
ab = 8
# Расстояние от Д до Г
dg = 15
# Расстояние от В до Г
vg = 17
# Длина от Г до главной дороги: (ag + gb - ab) / 2
leg = (ag + gb - ab) / 2
# Путь от Д до точки, где ножка Г встречает главную дорогу
d_to_junction = dg - leg
# Путь от В до той же точки
v_to_junction = vg - leg
# Складываем два куска главной дороги — это расстояние Д–В
print(d_to_junction + v_to_junction)
