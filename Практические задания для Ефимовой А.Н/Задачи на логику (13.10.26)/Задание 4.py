n = 0                                  # счётчик номера имени, пока 0
for a in "XYZ":                        # 1-я буква: X, потом Y, потом Z
    for b in "XYZ":                    # 2-я буква: тоже перебираем X, Y, Z
        for c in "XYZ":                # 3-я буква
            for d in "XYZ":            # 4-я буква
                for e in "XYZ":        # 5-я буква (меняется быстрее всех, как на экране)
                    n = n + 1          # переходим к следующему имени, номер растёт на 1
                    if n == 179:       # если это имя под номером 179
                        print(a + b + c + d + e)  # склеиваем 5 букв и выводим