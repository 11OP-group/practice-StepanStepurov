rating = input("Введите рейтинг продукта (от 1 до 10): ")

match rating:
    case "9" | "10":
        result = "Отличный продукт! 🌟 Настоятельно рекомендую!"
    case "7" | "8":
        result = "Хороший продукт! 😊 Рекомендую"
    case "4" | "5" | "6":
        result = "Средний продукт 😐 Можно попробовать"
    case "1" | "2" | "3":
        result = "Плохой продукт ❌ Не рекомендую"
    case _:
      
        result = "❌ Ошибка: введите число от 1 до 10"

print(f"Рейтинг {rating} → {result}")
