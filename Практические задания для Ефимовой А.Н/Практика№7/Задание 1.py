rating = int(input("Введите рейтинг от 1 до 10: "))

match rating:
    case 9 | 10:
        print("🌟 Отличный. Рекомендую!")
    case 7 | 8:
        print("😊 Хороший. Рекомендую!")
    case 5 | 6:
        print("😐 Средний. Можно попробовать.")
    case 1 | 2 | 3 | 4:
        print("👎 Плохой. Не рекомендую.")
    case _:
        print("❌ Ошибка! Введите число от 1 до 10.")
